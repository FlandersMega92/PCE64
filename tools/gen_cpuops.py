#!/usr/bin/env python3
"""Generate core/cpu_ops.inc: one threaded handler per HuC6280 opcode.
Reuses the opcode table from gen_cputab.py (imported by exec)."""
import sys, os

spec = {}
src = open(os.path.join(os.path.dirname(__file__), "gen_cputab.py")).read()
src = src[:src.index("ops = []")]
ns = {}
exec(src, ns)
tab = ns["tab"]
for c in range(256):
    if c not in tab:
        tab[c] = ("NOP", "IMP", 2)

READ = {"LDA", "LDX", "LDY", "ORA", "AND", "EOR", "ADC", "SBC", "CMP", "CPX", "CPY", "BIT"}
RMW = {"ASL", "LSR", "ROL", "ROR", "INC", "DEC", "TSB", "TRB", "RMB", "SMB"}
STORE = {"STA": "A", "STX": "X", "STY": "Y", "STZ": "0"}

def ea_code(mode):
    """returns (code, is_zp)"""
    if mode == "ZP":  return "unsigned ea = *pc++;", True
    if mode == "ZPX": return "unsigned ea = (uint8_t)(*pc++ + X);", True
    if mode == "ZPY": return "unsigned ea = (uint8_t)(*pc++ + Y);", True
    if mode == "ABS": return "unsigned ea = pc[0] | pc[1] << 8; pc += 2;", False
    if mode == "ABX": return "unsigned ea = ((pc[0] | pc[1] << 8) + X) & 0xFFFF; pc += 2;", False
    if mode == "ABY": return "unsigned ea = ((pc[0] | pc[1] << 8) + Y) & 0xFFFF; pc += 2;", False
    if mode == "IZX": return "unsigned z = (uint8_t)(*pc++ + X); unsigned ea = ram[z] | ram[(uint8_t)(z + 1)] << 8;", False
    if mode == "IZY": return "unsigned z = *pc++; unsigned ea = ((ram[z] | ram[(uint8_t)(z + 1)] << 8) + Y) & 0xFFFF;", False
    if mode == "IZP": return "unsigned z = *pc++; unsigned ea = ram[z] | ram[(uint8_t)(z + 1)] << 8;", False
    raise ValueError(mode)

ALU = {
    "LDA": "A = v; SETNZ(A);", "LDX": "X = v; SETNZ(X);", "LDY": "Y = v; SETNZ(Y);",
    "ORA": "ORA_(v);", "AND": "AND_(v);", "EOR": "EOR_(v);", "ADC": "ADC_(v);", "SBC": "SBC_(v);",
    "CMP": "CMP(A, v);", "CPX": "CMP(X, v);", "CPY": "CMP(Y, v);",
    "BIT": "fn = v; fv = v & 0x40; fz = A & v;",
}
RMWOP = {
    "ASL": "v = ASL(v);", "LSR": "v = LSR(v);", "ROL": "v = ROL(v);", "ROR": "v = ROR(v);",
    "INC": "v = INCV(v);", "DEC": "v = DECV(v);",
    "TSB": "fz = A & v; fn = v; fv = v & 0x40; v |= A;",
    "TRB": "fz = A & v; fn = v; fv = v & 0x40; v &= ~A;",
}

IMPL = {
    "ASLA": "A = ASL(A);", "LSRA": "A = LSR(A);", "ROLA": "A = ROL(A);", "RORA": "A = ROR(A);",
    "INA": "A = INCV(A);", "DEA": "A = DECV(A);",
    "INX": "X = (uint8_t)(X + 1); SETNZ(X);", "INY": "Y = (uint8_t)(Y + 1); SETNZ(Y);",
    "DEX": "X = (uint8_t)(X - 1); SETNZ(X);", "DEY": "Y = (uint8_t)(Y - 1); SETNZ(Y);",
    "PHA": "PUSH(A);", "PHX": "PUSH(X);", "PHY": "PUSH(Y);", "PHP": "PUSH(GETP() | FB);",
    "PLA": "A = PULL(); SETNZ(A);", "PLX": "X = PULL(); SETNZ(X);", "PLY": "Y = PULL(); SETNZ(Y);",
    "TAX": "X = A; SETNZ(X);", "TAY": "Y = A; SETNZ(Y);", "TXA": "A = X; SETNZ(A);", "TYA": "A = Y; SETNZ(A);",
    "TSX": "X = S; SETNZ(X);", "TXS": "S = X;",
    "SAX": "{ unsigned t = A; A = X; X = t; }", "SAY": "{ unsigned t = A; A = Y; Y = t; }",
    "SXY": "{ unsigned t = X; X = Y; Y = t; }",
    "CLA": "A = 0;", "CLX": "X = 0;", "CLY": "Y = 0;",
    "CLC": "fc = 0;", "SEC": "fc = 1;", "SEI": "fi = 1;", "CLV": "fv = 0;", "CLD": "fd = 0;", "SED": "fd = 1;",
    "NOP": "",
}

out = ["/* generated by tools/gen_cpuops.py: threaded HuC6280 handlers (shared tails) */"]
labels = []
def ea_only(mode):
    if mode == "ZP":  return "ea = *pc++;"
    if mode == "ZPX": return "ea = (uint8_t)(*pc++ + X);"
    if mode == "ZPY": return "ea = (uint8_t)(*pc++ + Y);"
    if mode == "ABS": return "ea = pc[0] | pc[1] << 8; pc += 2;"
    if mode == "ABX": return "ea = ((pc[0] | pc[1] << 8) + X) & 0xFFFF; pc += 2;"
    if mode == "ABY": return "ea = ((pc[0] | pc[1] << 8) + Y) & 0xFFFF; pc += 2;"
    if mode == "IZX": return "{ unsigned z = (uint8_t)(*pc++ + X); ea = ram[z] | ram[(uint8_t)(z + 1)] << 8; }"
    if mode == "IZY": return "{ unsigned z = *pc++; ea = ((ram[z] | ram[(uint8_t)(z + 1)] << 8) + Y) & 0xFFFF; }"
    if mode == "IZP": return "{ unsigned z = *pc++; ea = ram[z] | ram[(uint8_t)(z + 1)] << 8; }"
    raise ValueError(mode)
ZPM = ("ZP", "ZPX", "ZPY")
tails = []
used_tails = set()
for c in range(256):
    name, mode, cyc = tab[c]
    L = f"op_{c:02x}"
    labels.append(L)
    b = []
    if name in IMPL:
        b += [IMPL[name], f"cyc -= {cyc};", "NEXT;"]
    elif name in READ:
        if mode == "IMM":
            b += ["v = *pc++;"]
        elif mode in ZPM:
            b += [ea_only(mode), "v = ram[ea];"]
        else:
            b += [ea_only(mode), f"cyc -= {cyc};", f"goto rd_{name.lower()};"]
            used_tails.add(("rd", name))
            out.append(f"{L}: {{ " + " ".join(b) + " }")
            continue
        b += [f"cyc -= {cyc};", f"goto do_{name.lower()};"]
        used_tails.add(("do", name))
    elif name in STORE:
        b += [ea_only(mode)]
        val = STORE[name]
        if mode in ZPM:
            b += [f"ram[ea] = {val};", f"cyc -= {cyc};", "NEXT;"]
        else:
            b += [f"cyc -= {cyc};", f"goto wr_{val if val != '0' else 'z'};"]
            used_tails.add(("wr", val))
    elif name in RMW:
        if name in ("RMB", "SMB"):
            bit = (c >> 4) & 7
            b += ["ea = *pc++;", f"ram[ea] {'&= ~' if name == 'RMB' else '|= '}{1 << bit}u;", f"cyc -= {cyc};", "NEXT;"]
        elif mode in ZPM:
            b += [ea_only(mode), f"cyc -= {cyc};", f"goto zrmw_{name.lower()};"]
            used_tails.add(("zrmw", name))
        else:
            b += [ea_only(mode), f"cyc -= {cyc};", f"goto rmw_{name.lower()};"]
            used_tails.add(("rmw", name))
    elif name == "TST":
        b.append(f"cyc -= {cyc};")
        b.append("v = *pc++;")
        if c == 0x83: b.append("ea = ram[*pc++];")
        elif c == 0xA3: b.append("ea = ram[(uint8_t)(*pc++ + X)];")
        elif c == 0x93: b.append("ea = RD(pc[0] | pc[1] << 8); pc += 2;")
        else: b.append("ea = RD(((pc[0] | pc[1] << 8) + X) & 0xFFFF); pc += 2;")
        b += ["fn = ea; fv = ea & 0x40; fz = v & ea;", "NEXT;"]
    elif name in ("BBR", "BBS"):
        bit = (c >> 4) & 7
        cond = f"!(ram[pc[0]] & {1 << bit}u)" if name == "BBR" else f"(ram[pc[0]] & {1 << bit}u)"
        b += [f"cyc -= {cyc};", f"if ({cond}) goto take3;", "pc += 2;", "NEXT;"]
    elif name == "BCC_":
        cond = {0x10: "!(fn & 0x80)", 0x30: "(fn & 0x80)", 0x50: "!fv", 0x70: "fv",
                0x90: "!fc", 0xB0: "fc", 0xD0: "(fz & 0xFF)", 0xF0: "!(fz & 0xFF)"}[c]
        b += [f"cyc -= {cyc};", f"if ({cond}) goto take2;", "pc++;", "NEXT;"]
    elif name == "BRA":
        b += [f"cyc -= {cyc};", "goto take2;"]
    else:
        b.append(f"goto x_{name.lower()};  /* {cyc} cycles, in cpu.c */")
    out.append(f"{L}: {{ " + " ".join(b) + " }")

out.append("    /* shared tails */")
for kind, name in sorted(used_tails):
    if kind == "rd":
        out.append(f"rd_{name.lower()}: v = RD(ea); goto do_{name.lower()};")
        if ("do", name) not in used_tails:
            used_tails.add(("do", name))
for kind, name in sorted(used_tails):
    if kind == "do":
        if name in ("ORA", "AND", "EOR", "ADC"):
            out.append(f"do_{name.lower()}: if (UNLIKELY(tm)) {{ unsigned _sa = A; A = ram[X]; {ALU[name]} ram[X] = A; A = _sa; cyc -= 3; tm = 0; NEXT; }} {ALU[name]} NEXT;")
        else:
            out.append(f"do_{name.lower()}: {ALU[name]} NEXT;")
    elif kind == "wr":
        lab = name if name != "0" else "z"
        out.append(f"wr_{lab}: WR(ea, {name}); NEXT;")
    elif kind == "zrmw":
        out.append(f"zrmw_{name.lower()}: v = ram[ea]; {RMWOP[name]} ram[ea] = v; NEXT;")
    elif kind == "rmw":
        out.append(f"rmw_{name.lower()}: v = RD(ea); {RMWOP[name]} WR(ea, v); NEXT;")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
open(sys.argv[1].replace("cpu_ops.inc", "cpu_disp.h"), "w").write(
    "/* generated by tools/gen_cpuops.py */\n#define DISPATCH_TABLE { " + ", ".join("&&" + l for l in labels) + " }\n")
special = sorted({tab[c][0] for c in range(256)} - set(IMPL) - READ - set(STORE) - RMW - {"TST", "BBR", "BBS", "BCC_", "BRA"})
print("special handlers needed:", " ".join("x_" + s.lower() for s in special))
